#!/usr/bin/env node
/**
 * M8.2 — assemble the throwaway QG-03 probe extensions, one Chromium and one Firefox per candidate.
 *
 * Follows W1-QG03's build (build-qg03-extension.mjs) and departs from it only where stated:
 *   - the shipped `dist/` of @pratibimb/security and @pratibimb/perception goes in VERBATIM;
 *   - the CSP comes from the SHIPPED buildExtensionPagesCsp;
 *   - W1-QG03's qg03-instrument.js is copied VERBATIM (memory, network and GPU hooks);
 *   - DEPARTURE: model bytes and input tensors are packaged as extension files and read
 *     same-origin, rather than inlined as base64 — the inputs are 8–12 MB each. A same-origin
 *     extension read is not egress, and the instrumented network log shows it as such.
 *   - the M8.1 functions (dbPostprocess, tensorStats, judgeWasm) are injected as their SOURCE TEXT,
 *     taken from the committed module at build time; the sha256 of each is recorded, so the
 *     post-processing benchmarked here is provably the one screened.
 *
 * Output (git-ignored): ../models/ext/<candidate>/{chrome,firefox}/ and ../models/ext/build.json.
 * Prerequisites: npm run typecheck (dist/), prepare-fixtures.mjs (tensors).
 */
import { copyFileSync, cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { REDACTION_CRITERIA } from "../../../../tests/browser/support/redaction-metrics.mjs";
import { DB_POSTPROCESS, dbPostprocess, judgeWasm, tensorStats } from "../../../../tests/browser/support/text-detector-screening.mjs";
import { baselinePath, fixturesDir, integrityRecordPath } from "../../../../tests/browser/support/m82-baseline.mjs";
import { resolveWorkstation } from "../../../../tests/browser/support/workstation.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const EXP = dirname(HERE);
const ROOT = join(EXP, "..", "..", "..");
const M81 = join(ROOT, "artifacts", "experiments", "M8.1-visual-text-screening");
const WS = resolveWorkstation();
const FIX = fixturesDir(WS);
const OUT = join(EXP, "models", "ext");
const ORT_DIST = join(ROOT, "node_modules", "onnxruntime-web", "dist");
const INSTRUMENT = join(ROOT, "artifacts", "experiments", "W1-QG03-t1-detector-runtime", "harness", "qg03-instrument.js");
export const PORT = 8913;
const sha256 = (b) => createHash("sha256").update(b).digest("hex");
const must = (p, hint) => {
  if (!existsSync(p)) {
    console.error(`missing: ${p}\n  ${hint}`);
    process.exit(1);
  }
  return p;
};
must(join(ROOT, "packages/security/dist/src/index.js"), "run: npm run typecheck");
must(join(ROOT, "packages/perception/dist/src/index.js"), "run: npm run typecheck");
must(integrityRecordPath(WS), "run: prepare-fixtures.mjs");
must(baselinePath("TR-01", WS), "run: prepare-fixtures.mjs --establish-baseline");

const { buildExtensionPagesCsp } = await import(pathToFileURL(join(ROOT, "packages/security/dist/src/index.js")).href);
const CSP = buildExtensionPagesCsp(`http://127.0.0.1:${PORT}`);
const ORT_FILES = ["ort.all.min.js", "ort-wasm-simd-threaded.mjs", "ort-wasm-simd-threaded.wasm", "ort-wasm-simd-threaded.jsep.mjs", "ort-wasm-simd-threaded.jsep.wasm"];

const lib = {
  dbPostprocess: dbPostprocess.toString(),
  tensorStats: tensorStats.toString(),
  judgeWasm: judgeWasm.toString(),
};
const libJs = [
  "// GENERATED by build-extension.mjs from tests/browser/support/text-detector-screening.mjs — source text, verbatim.",
  `const REDACTION_CRITERIA = ${JSON.stringify({ wasmRtolSumAbs: REDACTION_CRITERIA.wasmRtolSumAbs })};`,
  `const DB_POSTPROCESS = ${JSON.stringify(DB_POSTPROCESS)};`,
  lib.dbPostprocess,
  lib.tensorStats,
  lib.judgeWasm,
  "globalThis.M82_LIB = { DB_POSTPROCESS, dbPostprocess, tensorStats, judgeWasm };",
  "",
].join("\n");

const MODELS = {
  "TR-01": { stem: "tr01_ppocrv4_mobile_det", rule: { type: 2, resize_long: 960, stride: 128 } },
  "TR-02": { stem: "tr02_ppocrv3_mobile_det", rule: { type: 0, limit_side_len: 736, limit_type: "min", stride: 32, max_side_limit: 4000 } },
};
const UI_HEAD = join(ROOT, "artifacts", "models", "t1-ui-head", "t1-ui-head.onnx");
const YUNET = join(ROOT, "artifacts", "models", "yunet", "yunet.onnx");
const FROZEN = {
  uiHead: { sha256: "ba6d9e93695b22d17d9dc2b8193966132af85a6a031b08eb453d1d20a05179d0", bytes: 302960 },
  yunet: { sha256: "8f2383e4dd3cfbb4553ea8718107fc0423210dc964f9f4280604804ed2552fa4", bytes: 232589 },
};
for (const [k, p] of [["uiHead", UI_HEAD], ["yunet", YUNET]]) {
  const b = readFileSync(must(p, "see protocol.md §2"));
  if (sha256(b) !== FROZEN[k].sha256 || b.length !== FROZEN[k].bytes) {
    console.error(`REFUSING: ${p} is not the frozen ${k}`);
    process.exit(1);
  }
}

const build = { csp: CSP, port: PORT, lib: Object.fromEntries(Object.entries(lib).map(([k, v]) => [k, sha256(v)])), instrumentSha256: sha256(readFileSync(INSTRUMENT)), candidates: {} };
const integrity = JSON.parse(readFileSync(integrityRecordPath(WS), "utf8"));

for (const [cid, spec] of Object.entries(MODELS)) {
  const dir = join(FIX, cid);
  const nat = JSON.parse(readFileSync(join(dir, "native-reference.json"), "utf8"));
  // The WASM reference hashes below exist only in M8.1's W1 record. M8.2's own browser cells have
  // not been re-run on another workstation, so rather than substitute a null and build a reference
  // that silently compares nothing, this REFUSES and names what would have to be produced first.
  if (WS.id !== "W1") {
    console.error(
      `missing: an M8.2 WASM reference for ${cid} on ${WS.id}.
` +
        "  build-extension.mjs needs `inputs[*].wasm.outputSha256`, which only M8.2's own browser cells
" +
        "  produce; the M8.2 cells have not been re-run on this machine. It refuses rather than emitting a
" +
        "  reference whose WASM comparison is empty. Re-run M8.2's browser cells here, or run on W1."
    );
    process.exit(1);
  }
  const m81 = JSON.parse(readFileSync(join(M81, "results", `${cid.toLowerCase()}-run1.json`), "utf8"));
  const modelBytes = readFileSync(join(dir, "model.onnx"));
  const inputs = {};
  for (const [name, v] of Object.entries(nat.inputs)) {
    inputs[name] = {
      inputSha256: v.input_sha256,
      shape: v.meta.shape,
      meta: name === "synthetic" ? null : { source_hw: v.meta.source_hw, ratio_h: v.meta.ratio_h, ratio_w: v.meta.ratio_w, resized_hw: v.meta.resized_hw },
      native: { count: v.native_output.count, sumAbs: v.native_output.sumAbs, outputs: v.output_count, outputSha256: v.native_output_sha256 },
      m81: { wasmOutputSha256: m81.inputs[name].wasm.outputSha256, boxesSha256: m81.inputs[name].boxesSha256 ?? null },
    };
  }
  const ref = {
    candidate: cid,
    model: { file: "candidate.onnx", sha256: integrity.candidates[cid].modelSha256, bytes: modelBytes.length },
    uiHead: { file: "t1-ui-head.onnx", ...FROZEN.uiHead },
    yunet: { file: "yunet.onnx", ...FROZEN.yunet },
    preprocessRule: spec.rule,
    heldOut: ["H1", "H2", "H3", "H4", "H5", "H6"],
    inputs,
  };
  const refJs = `// GENERATED by build-extension.mjs — do not edit.\nglobalThis.M82_REF = ${JSON.stringify(ref)};\n`;
  build.candidates[cid] = { refSha256: sha256(refJs), modelSha256: ref.model.sha256 };

  for (const browser of ["chrome", "firefox"]) {
    const out = join(OUT, cid, browser);
    rmSync(out, { recursive: true, force: true });
    mkdirSync(join(out, "models"), { recursive: true });
    mkdirSync(join(out, "fixtures"), { recursive: true });
    for (const f of ORT_FILES) copyFileSync(must(join(ORT_DIST, f), "npm install"), join(out, f));
    cpSync(join(ROOT, "packages/security/dist/src"), join(out, "security"), { recursive: true });
    cpSync(join(ROOT, "packages/perception/dist/src"), join(out, "perception"), { recursive: true });
    for (const sub of ["security", "perception", "security/generated"]) {
      const d = join(out, sub);
      if (existsSync(d)) for (const f of readdirSync(d)) if (f.endsWith(".d.ts") || f.endsWith(".map")) rmSync(join(d, f));
    }
    copyFileSync(INSTRUMENT, join(out, "m82-instrument.js"));
    copyFileSync(join(HERE, "m82-probe.js"), join(out, "m82-probe.js"));
    copyFileSync(join(HERE, "m82-preprocess.js"), join(out, "m82-preprocess.js"));
    writeFileSync(join(out, "m82-lib.js"), libJs);
    writeFileSync(join(out, "m82-ref.js"), refJs);
    copyFileSync(join(dir, "model.onnx"), join(out, "models", "candidate.onnx"));
    copyFileSync(UI_HEAD, join(out, "models", "t1-ui-head.onnx"));
    copyFileSync(YUNET, join(out, "models", "yunet.onnx"));
    for (const name of ["dev", ...ref.heldOut]) copyFileSync(join(dir, `input-${name}.f32`), join(out, "fixtures", `input-${name}.f32`));
    copyFileSync(join(FIX, "screenshots", "dev.png"), join(out, "fixtures", "dev.png"));
    const scripts = ["m82-instrument.js", "ort.all.min.js", "m82-lib.js", "m82-ref.js", "m82-preprocess.js", "m82-probe.js"];

    if (browser === "chrome") {
      writeFileSync(join(out, "manifest.json"), JSON.stringify({
        manifest_version: 3,
        name: `PratiBimb M8.2 QG-03 probe ${cid} (Chrome)`,
        version: "1.0.0",
        description: "Throwaway QG-03 feasibility harness. Never shipped.",
        minimum_chrome_version: "116",
        background: { service_worker: "background.js" },
        permissions: ["offscreen"],
        host_permissions: [`http://127.0.0.1:${PORT}/*`],
        content_security_policy: { extension_pages: CSP },
      }, null, 2));
      // ORDER IS LOAD-BEARING: the instrument must wrap WebAssembly.Memory before ORT loads.
      writeFileSync(join(out, "offscreen.html"), `<!doctype html><meta charset="utf-8"><title>m82</title>${scripts.map((s) => `<script src="${s}"></script>`).join("")}<script src="offscreen.js"></script>`);
      writeFileSync(join(out, "offscreen.js"), [
        "chrome.runtime.onMessage.addListener((msg) => {",
        '  if (!msg || msg.type !== "m82-go") return;',
        "  (async () => {",
        "    let r;",
        '    try { r = await globalThis.runM82("chrome-offscreen-document", Object.assign({ base: chrome.runtime.getURL("") }, msg.config)); }',
        '    catch (e) { r = { context: "chrome-offscreen-document", conclusion: "probe threw", errors: [String((e && e.message) || e).slice(0, 400)] }; }',
        '    chrome.runtime.sendMessage({ type: "m82-result", result: r });',
        "  })();",
        "});",
      ].join("\n"));
      writeFileSync(join(out, "background.js"), [
        "// MV3 service worker: drives the offscreen document; it never runs ORT itself.",
        "async function ensureOffscreen() {",
        '  const has = await chrome.runtime.getContexts({ contextTypes: ["OFFSCREEN_DOCUMENT"] });',
        "  if (has.length) return false;",
        '  await chrome.offscreen.createDocument({ url: "offscreen.html", reasons: ["WORKERS"], justification: "M8.2 QG-03 probe" });',
        "  return true;",
        "}",
        "function ask(config) {",
        "  return new Promise((resolve) => {",
        '    const t = setTimeout(() => resolve({ conclusion: "offscreen timeout", errors: ["no reply"] }), 900000);',
        "    chrome.runtime.onMessage.addListener(function h(m) {",
        '      if (m && m.type === "m82-result") { clearTimeout(t); chrome.runtime.onMessage.removeListener(h); resolve(m.result); }',
        "    });",
        '    chrome.runtime.sendMessage({ type: "m82-go", config }).catch(() => {});',
        "  });",
        "}",
        "globalThis.__m82_run = async function (config) {",
        "  await ensureOffscreen();",
        "  const r = await ask(config);",
        '  if (config.mode === "teardown" && config.contextTeardown) {',
        "    // Context teardown: close the offscreen document, make a new one, run one more cycle.",
        "    await chrome.offscreen.closeDocument();",
        "    const gone = (await chrome.runtime.getContexts({ contextTypes: [\"OFFSCREEN_DOCUMENT\"] })).length === 0;",
        "    const created = await ensureOffscreen();",
        '    const fresh = await ask(Object.assign({}, config, { mode: "teardown-fresh" }));',
        "    r.contextTeardown = { closed: gone, recreated: created, result: fresh };",
        "  }",
        "  return r;",
        "};",
      ].join("\n"));
    } else {
      writeFileSync(join(out, "manifest.json"), JSON.stringify({
        manifest_version: 3,
        name: `PratiBimb M8.2 QG-03 probe ${cid} (Firefox)`,
        version: "1.0.0",
        description: "Throwaway QG-03 feasibility harness. Never shipped.",
        browser_specific_settings: { gecko: { id: `pratibimb-m82-${cid.toLowerCase()}@example.invalid`, strict_min_version: "128.0" } },
        background: { scripts: ["m82-config.js", ...scripts, "ff-background.js"] },
        permissions: ["tabs"],
        host_permissions: [`http://127.0.0.1:${PORT}/*`],
        content_security_policy: { extension_pages: CSP },
      }, null, 2));
      writeFileSync(join(out, "m82-config.js"), "globalThis.M82_CONFIG = null; // written by the runner before each launch\n");
      writeFileSync(join(out, "ff-background.js"), [
        "// Firefox MV3 event page. Reports over fetch, falling back to chunked tab beacons, because",
        "// Firefox MV3 gates host_permissions behind origin controls (S-02a-2; W1-QG03's method).",
        "const api = typeof browser !== \"undefined\" ? browser : chrome;",
        `const BASE = "http://127.0.0.1:${PORT}";`,
        "function beacon(q) { try { return api.tabs.create({ url: BASE + q, active: false }); } catch (e) { return Promise.resolve(); } }",
        "async function deliver(payload) {",
        "  const body = JSON.stringify(payload);",
        '  try { const res = await fetch(BASE + "/result", { method: "POST", headers: { "content-type": "application/json" }, body }); if (res && res.ok) return; } catch (e) {}',
        "  const enc = encodeURIComponent(body); const CH = 6000; const n = Math.ceil(enc.length / CH); const id = \"m82-\" + Date.now();",
        '  for (let i = 0; i < n; i++) await beacon("/chunk?id=" + id + "&i=" + i + "&n=" + n + "&d=" + enc.slice(i * CH, (i + 1) * CH));',
        "}",
        "(async () => {",
        '  await beacon("/alive");',
        "  const cfg = globalThis.M82_CONFIG;",
        "  let r;",
        '  try { r = await globalThis.runM82("firefox-mv3-event-page", Object.assign({ base: api.runtime.getURL("") }, cfg)); }',
        '  catch (e) { r = { context: "firefox-mv3-event-page", conclusion: "probe threw", errors: [String((e && e.message) || e).slice(0, 400)] }; }',
        "  await deliver(r);",
        "})();",
      ].join("\n"));
    }
  }
}
mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, "build.json"), JSON.stringify(build, null, 1));
console.log(JSON.stringify(build, null, 1));
